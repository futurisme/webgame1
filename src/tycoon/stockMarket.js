/**
 * Autonomous Competitor AI Strategy Evaluator.
 * Simulates real corporate defensive and offensive moves by rival companies.
 * @param {Object} comp
 * @param {string} marketSentiment
 * @returns {Object|null}
 */
export function evaluateCompetitorStrategicMove(comp, marketSentiment) {
  if (comp.isAcquiredByPlayer) return null;

  const playerOwnershipPct = (comp.playerOwnedShares / comp.totalShares) * 100;

  // 1. Hostile Takeover Defense AI
  if (playerOwnershipPct >= 20 && !comp.alertThresholdPassed) {
    comp.alertThresholdPassed = true;
    return {
      type: 'TAKEOVER_ALERT',
      message: `Dewan Komisaris ${comp.symbol} (${comp.name}) menggelar rapat darurat menyusul akumulasi ${playerOwnershipPct.toFixed(1)}% saham oleh entitas luar!`,
      priceImpact: 0.04,
    };
  }

  if (playerOwnershipPct >= 35 && Math.random() < 0.15) {
    return {
      type: 'POISON_PILL_DEFENSE',
      message: `CEO ${comp.ceo?.name || 'Komisaris'} (${comp.symbol}) mengesahkan program Share Buyback defensif untuk menaikkan harga saham dan mempersulit hostile takeover!`,
      priceImpact: 0.08,
    };
  }

  // 2. Periodic Corporate Developments
  if (Math.random() < 0.02) {
    const isPositive = Math.random() > 0.35;
    const impact = isPositive ? (0.03 + Math.random() * 0.05) : (-0.02 - Math.random() * 0.04);
    const messages = isPositive ? [
      `${comp.name} (${comp.symbol}) menandatangani kontrak strategis baru yang menaikkan proyeksi laba tahunan!`,
      `CEO ${comp.ceo?.name} (${comp.symbol}) memaparkan terobosan efisiensi operasional pada paparan publik kuartalan.`,
      `${comp.symbol} berhasil membukukan kenaikan margin EBITDA di atas konsensus analis pasar modal.`,
    ] : [
      `${comp.name} (${comp.symbol}) mengalami penundaan jadwal rantai pasok kuartal ini.`,
      `Regulator pasar modal meminta klarifikasi kepatuhan operasional dari manajemen ${comp.symbol}.`,
      `${comp.symbol} mencatat peningkatan biaya riset yang menekan margin kas sementara.`,
    ];

    return {
      type: 'CORPORATE_UPDATE',
      message: messages[Math.floor(Math.random() * messages.length)],
      priceImpact: impact,
    };
  }

  return null;
}

/**
 * Generates the next realistic price candlestick for a stock ticker.
 * @param {number} prevClose
 * @param {number} [volatilityPct=0.03]
 * @param {number} [trendFactor=0.001]
 * @param {number} [shockFactor=0]
 * @returns {Object}
 */
export function generateNextCandle(prevClose, volatilityPct = 0.03, trendFactor = 0.001, shockFactor = 0) {
  const randomDrift = (Math.random() - 0.49) * volatilityPct * 2;
  const netDeltaPct = trendFactor + randomDrift + shockFactor;
  const newClose = Math.max(0.50, Math.round(prevClose * (1 + netDeltaPct) * 100) / 100);

  const highDelta = Math.abs(newClose - prevClose) * (1 + Math.random() * 0.8) + (prevClose * 0.005);
  const lowDelta = Math.abs(newClose - prevClose) * (1 + Math.random() * 0.8) + (prevClose * 0.005);

  const open = prevClose;
  const high = Math.round((Math.max(open, newClose) + highDelta) * 100) / 100;
  const low = Math.round((Math.max(0.20, Math.min(open, newClose) - lowDelta)) * 100) / 100;
  const volume = Math.round(15000 + Math.random() * 95000);

  return {
    timestamp: Date.now(),
    open,
    high,
    low,
    close: newClose,
    volume,
  };
}

/**
 * Generates synthetic initial candlestick history for a given base price.
 * @param {number} basePrice
 * @param {number} [count=24]
 * @returns {Array<Object>}
 */
export function generateInitialCandleHistory(basePrice, count = 24) {
  const history = [];
  const baseTime = Date.now() - count * 60 * 1000;
  let p = basePrice;
  for (let i = 0; i < count; i++) {
    const change = (Math.random() - 0.49) * 0.04;
    const open = p;
    const close = Math.round(Math.max(0.5, p * (1 + change)) * 100) / 100;
    const high = Math.round((Math.max(open, close) + Math.random() * 0.8) * 100) / 100;
    const low = Math.round((Math.max(0.2, Math.min(open, close) - Math.random() * 0.8)) * 100) / 100;
    history.push({
      timestamp: baseTime + i * 60 * 1000,
      open,
      high,
      low,
      close,
      volume: Math.round(20000 + Math.random() * 60000),
    });
    p = close;
  }
  return history;
}

/**
 * Checks if player has achieved controlling majority (>50%) or supermajority (>=67%).
 * @param {number} ownedShares
 * @param {number} totalShares
 * @returns {{hasControllingStake: boolean, ownershipPct: number, canMerge: boolean}}
 */
export function checkControllingStake(ownedShares, totalShares) {
  if (totalShares <= 0) return { hasControllingStake: false, ownershipPct: 0, canMerge: false };
  const ownershipPct = Math.round((ownedShares / totalShares) * 10000) / 100;
  return {
    hasControllingStake: ownershipPct > 50,
    ownershipPct,
    canMerge: ownershipPct >= 67,
  };
}

/**
 * Processes a buy order for shares.
 * @param {number} playerCash
 * @param {Object} stock
 * @param {number} sharesToBuy
 * @returns {Object}
 */
export function executeStockBuy(playerCash, stock, sharesToBuy) {
  if (sharesToBuy <= 0 || isNaN(sharesToBuy)) {
    return {
      success: false,
      totalCost: 0,
      newPlayerCash: playerCash,
      newPlayerShares: stock.playerOwnedShares,
      errorMessage: 'Jumlah lembar saham tidak valid.',
    };
  }
  const totalCost = Math.round(sharesToBuy * stock.price * 100) / 100;
  if (playerCash < totalCost) {
    return {
      success: false,
      totalCost,
      newPlayerCash: playerCash,
      newPlayerShares: stock.playerOwnedShares,
      errorMessage: 'Saldo kas likuid tidak mencukupi untuk pembelian ini.',
    };
  }
  return {
    success: true,
    totalCost,
    newPlayerCash: Math.round((playerCash - totalCost) * 100) / 100,
    newPlayerShares: stock.playerOwnedShares + sharesToBuy,
  };
}

/**
 * Processes a sell order for shares.
 * @param {number} playerCash
 * @param {Object} stock
 * @param {number} sharesToSell
 * @returns {Object}
 */
export function executeStockSell(playerCash, stock, sharesToSell) {
  if (sharesToSell <= 0 || isNaN(sharesToSell) || sharesToSell > stock.playerOwnedShares) {
    return {
      success: false,
      totalProceeds: 0,
      newPlayerCash: playerCash,
      newPlayerShares: stock.playerOwnedShares,
      errorMessage: 'Jumlah lembar saham yang dijual melebihi portofolio kepemilikan.',
    };
  }
  const totalProceeds = Math.round(sharesToSell * stock.price * 100) / 100;
  return {
    success: true,
    totalProceeds,
    newPlayerCash: Math.round((playerCash + totalProceeds) * 100) / 100,
    newPlayerShares: stock.playerOwnedShares - sharesToSell,
  };
}
